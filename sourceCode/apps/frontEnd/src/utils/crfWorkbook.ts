// Builds the Florida OIR Catastrophe Reporting Form (CRF-26A, version 26.01.A) workbook from claim data.
// Mirrors the tabs and column wording of OIR's 2026 CRF template (Version, Instructions, Contact and Statewide Modeling
// Information, Claims Data Extract, Validation Checks, Survey, Valid Responses). IRFS rejects a filing unless every
// validation shows TRUE, and OIR re-issues the template with each data call, so confirm against the template OIR sends.
import type { ComplianceSummary, SurveyData } from '../models/compliance/complianceModel';

export interface CrfContact {
  preparer: string; email: string; phone: string; companyName: string; naicCode: string; floridaCompanyCode: string; fein: string; groupCode: string; domicile: string;
  grossPayable: number; reinsurance: number; model: string; howEvaluated: string;
  longTerm?: string; demandSurge?: string; stormSurge?: string;
}

export const FL_COUNTIES = ['Alachua', 'Baker', 'Bay', 'Bradford', 'Brevard', 'Broward', 'Calhoun', 'Charlotte', 'Citrus', 'Clay', 'Collier', 'Columbia', 'DeSoto', 'Dixie', 'Duval',
  'Escambia', 'Flagler', 'Franklin', 'Gadsden', 'Gilchrist', 'Glades', 'Gulf', 'Hamilton', 'Hardee', 'Hendry', 'Hernando', 'Highlands', 'Hillsborough', 'Holmes', 'Indian River',
  'Jackson', 'Jefferson', 'Lafayette', 'Lake', 'Lee', 'Leon', 'Levy', 'Liberty', 'Madison', 'Manatee', 'Marion', 'Martin', 'Miami-Dade', 'Monroe', 'Nassau', 'Okaloosa',
  'Okeechobee', 'Orange', 'Osceola', 'Palm Beach', 'Pasco', 'Pinellas', 'Polk', 'Putnam', 'Santa Rosa', 'Sarasota', 'Seminole', 'St. Johns', 'St. Lucie', 'Sumter', 'Suwannee',
  'Taylor', 'Union', 'Volusia', 'Wakulla', 'Walton', 'Washington'];

// Template line-of-business columns, in template order. We write HO, DW and PF; the rest are reported as zero.
export const LOB_LIST: [string, string][] = [
  ['HO', 'Homeowners'], ['DW', 'Dwelling'], ['MHO', 'Mobile Homeowners'], ['CR', 'Commercial Residential'], ['CP', 'Commercial Property'],
  ['PF', 'Private Flood - Stand-Alone'], ['BI', 'Business Interruption - Stand-Alone'], ['PPAD', 'Private Passenger Auto Physical Damage'],
  ['CPD', 'Commercial Auto Physical Damage'], ['OM', 'Other Lines of Business'],
];
export const LOB_CODES = LOB_LIST.map(([c]) => c);

const USD = '$#,##0';
const PCT = '0.0%';
const mdy = (iso: string): string => { const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso); return m ? `${m[2]}/${m[3]}/${m[1]}` : iso; };
const cut = (t: string, n = 250): string => (t.length > n ? t.slice(0, n) : t);

interface Cell { v?: unknown; f?: string; z?: string; t?: string }
type Row = (Cell | string | number | boolean | null)[];

function emptySurvey(): SurveyData {
  return { closedWithPaymentByDays: [0, 0, 0, 0], closedWithoutPaymentByDays: [0, 0, 0, 0], openInAppraisal: 0, openInLitigation: 0, openAttorneyRepresented: 0,
    openPublicAdjuster: 0, openWaitingOnContractors: 0, openWindVsFlood: 0, reopened: 0, supplemental: 0 };
}

export async function buildCrfWorkbook(s: ComplianceSummary, c: CrfContact, asOf: string): Promise<Blob> {
  const XLSX = await import('xlsx');
  const wb = XLSX.utils.book_new();
  const eventName = s.event?.eventName ?? 'ALL EVENTS';

  const sheet = (name: string, rows: Row[], widths: number[] = []) => {
    const ws: Record<string, unknown> = {};
    let maxC = 0;
    rows.forEach((row, r) => row.forEach((cell, col) => {
      if (cell === null || cell === undefined || cell === '') return;
      const ref = XLSX.utils.encode_cell({ r, c: col });
      maxC = Math.max(maxC, col);
      if (typeof cell === 'object') {
        const o: Record<string, unknown> = {};
        if (cell.f) { o['f'] = cell.f; o['t'] = cell.t ?? 'n'; } else { o['v'] = cell.v; o['t'] = typeof cell.v === 'number' ? 'n' : typeof cell.v === 'boolean' ? 'b' : 's'; }
        if (cell.z) o['z'] = cell.z;
        ws[ref] = o;
      } else ws[ref] = { v: cell, t: typeof cell === 'number' ? 'n' : typeof cell === 'boolean' ? 'b' : 's' };
    }));
    ws['!ref'] = XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: Math.max(rows.length - 1, 0), c: maxC } });
    if (widths.length) ws['!cols'] = widths.map((w) => ({ wch: w }));
    XLSX.utils.book_append_sheet(wb, ws as never, name);
  };
  const F = (f: string, z?: string, t = 'n'): Cell => ({ f, z, t });
  const bool = (f: string): Cell => F(f, undefined, 'b');

  // ── Version ──
  sheet('Version', [['Form Version', '26.01.A'], ['Trade Secret?', 'NO'], ['Agency', 'Florida Office of Insurance Regulation'], ['Event (Hurricane) Name', eventName.toUpperCase()],
    ['Note', 'Generated by LAELia from claim data. OIR re-issues the CRF template with each data call; confirm layout and numbering against the template OIR sends before filing in IRFS.']], [26, 90]);

  // ── Instructions ──
  sheet('Instructions', [['Data definitions applied in this workbook'],
    ['Amounts are in whole dollars. Paid loss is net of salvage and subrogation and excludes loss adjustment expense, which is reported separately.'],
    ['Claims are cumulative and reported as of the as-of date. Only Florida claims tied to the event are included; NFIP (SFIP) claims are federal and are excluded.'],
    ['County or ZIP is entered as "Unknown" only after reasonable effort to locate the loss.'],
    ['Row validations: (1) line of business is a valid code; (2) county and ZIP match the Valid Responses pairing; (3) open and closed categories sum to claims reported; (4) zero claims means zero paid loss; (5) no claims with payment means zero paid loss.'],
    ['IRFS accepts the filing only when every validation on every tab shows TRUE.']], [140]);

  // ── Claims Data Extract (detail) ──
  const extHead = ['Line of Business', 'County in Which Claim Occurred', 'Zip Code in Which Claim Occurred', 'Number of Claims Reported (Florida Only)', 'Number of Open Claims With Payment',
    'Number of Open Claims Without Payment', 'Number of Claims Closed With Payment', 'Number of Claims Closed Without Payment', 'Number of Claims Closed Without Payment (No Flood Coverage)',
    'Number of Claims Closed Without Payment (All Other Coverage Exclusions or No Policy in Force)', 'Number of Claims Closed Without Payment (Covered Damage Below Deductible)',
    'Number of Claims Closed Without Payment (Fraud)', 'Number of Claims Closed Without Payment (For Administrative Reasons)', 'Paid Loss Excluding Loss Adjustment Expense',
    'Trade Secret ?', 'Required Data Fields?', 'Required Data Matches LOB?', 'Required Data Matches County/Zip Codes?', 'Required Data Closed Claim Without Payment?',
    'Required Claims and Paid Losses?', 'Error Messages'];
  const ext: Row[] = [extHead];
  const n = s.rows.length;
  s.rows.forEach((x, i) => {
    const r = i + 2;
    const zip = x.zip && /^\d{5}$/.test(x.zip) ? x.zip : 'Unknown';
    ext.push([x.lob, x.county || 'Unknown', zip, x.claims, x.openPay, x.openNoPay, x.closedPay, x.closedNoPay, 0, x.closedNoPay, 0, 0, 0, { v: x.paidLoss, z: USD }, 'NO',
      bool(`AND(A${r}<>"",B${r}<>"",C${r}<>"",D${r}>=0,N${r}>=0)`),
      bool(`COUNTIF('Valid Responses'!A:A,A${r})>0`),
      bool(`COUNTIFS('Valid Responses'!C:C,B${r},'Valid Responses'!D:D,C${r})>0`),
      bool(`H${r}=SUM(I${r}:M${r})`),
      bool(`AND(E${r}+F${r}+G${r}+H${r}=D${r},IF(D${r}=0,N${r}=0,TRUE),IF(E${r}+G${r}=0,N${r}=0,TRUE))`),
      F(`IF(AND(P${r},Q${r},R${r},S${r},T${r}),"","Check row ${r}: "&IF(Q${r},"","line of business; ")&IF(R${r},"","county/ZIP pairing; ")&IF(S${r},"","closed without payment categories; ")&IF(T${r},"","claim counts and paid loss; "))`, undefined, 's')]);
  });
  ext.push(['Totals', '', '', ...['D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M'].map((col) => F(`SUM(${col}2:${col}${n + 1})`)), F(`SUM(N2:N${n + 1})`, USD)]);
  sheet('Claims Data Extract', ext, [16, 24, 14, ...Array(18).fill(18)]);

  // ── Contact and Statewide Modeling Information ──
  const net = c.grossPayable - c.reinsurance;
  const contact: Row[] = [['TRADE SECRET?', 'NO'], ['Contact and Statewide Modeling Information'], ['Field', 'Responses', 'Required Data', 'Field Complete?'],
    ['As-of date of the data submitted (MM/DD/YYYY)', mdy(asOf), 'Not Applicable', bool('LEN(B4)>0')],
    ['Name of the individual who completed this form', c.preparer, 'Not Applicable', bool('LEN(B5)>0')],
    ["Individual's Email address", c.email, 'Not Applicable', bool('LEN(B6)>0')],
    ["Individual's Phone Number", c.phone, 'Not Applicable', bool('LEN(B7)>0')],
    ['Company Name', c.companyName, 'Not Applicable', bool('LEN(B8)>0')],
    ['Company NAIC Code', c.naicCode, 'Not Applicable', bool('LEN(B9)>0')],
    ['Company Florida Company Code', c.floridaCompanyCode, 'Not Applicable', bool('LEN(B10)>0')],
    ['Company FEIN', c.fein, 'Not Applicable', bool('LEN(B11)>0')],
    ['Company Group Code', c.groupCode, 'Not Applicable', bool('LEN(B12)>0')],
    ['Company State of Domicile', c.domicile, 'Not Applicable', bool('LEN(B13)>0')],
    ['Is this filing being submitted as trade secret?', 'No', 'No', bool('B14="No"')],
    ['Dollar Amount of Estimated Gross Payable Loss from Event (Gross of Reinsurance) (in whole dollars)', { v: c.grossPayable, z: USD }, 'Not Applicable', bool('ISNUMBER(B15)')],
    ['Projected Net Retention Resulting from the Event (in whole dollars)', { v: net, z: USD }, 'Not Applicable', bool('ISNUMBER(B16)')],
    ['Dollar Amount of Estimated Payable Loss from Event covered by Reinsurance or Other Loss-Transfer Agreements (in whole dollars)', { v: c.reinsurance, z: USD }, 'Not Applicable', bool('B15=B16+B17')],
    ['Model and Version. (maximum of 250 characters)', cut(c.model || 'N/A'), 'Not Applicable', bool('LEN(B18)>0')],
    ['Long-Term', c.longTerm ?? 'N/A', 'Not Applicable', bool('LEN(B19)>0')],
    ['Demand Surge', c.demandSurge ?? 'N/A', 'Not Applicable', bool('LEN(B20)>0')],
    ['Storm Surge (Flood only)', c.stormSurge ?? 'N/A', 'Not Applicable', bool('LEN(B21)>0')],
    ['If the Name and Version of Model Used for Financial Projections is N/A, how did the Company evaluate the losses reported? (maximum of 250 characters)', cut(c.howEvaluated), 'Not Applicable', bool('OR(B18<>"N/A",LEN(B22)>0)')],
    [''],
    ['Statewide totals by line of business (calculated from the Claims Data Extract)'],
    ['Validation Checks', 'Lines of Business', 'Policies in Force (Florida Only)', 'Number of Claims Reported (Florida Only)', 'Number of Open Claims with Payment', 'Number of Open Claims without Payment',
      'Number of Claims Closed with Payment', 'Number of Claims Closed without Payment', 'Number of Claims Closed Without Payment (No Flood Coverage)',
      'Number of Claims Closed Without Payment (All Other Coverage Exclusions or No Policy in Force)', 'Number of Claims Closed Without Payment (Covered Damage Below Deductible)',
      'Number of Claims Closed Without Payment (Fraud)', 'Number of Claims Closed Without Payment (For Administrative Reasons)', 'Percent of Claims Closed',
      'Paid Loss Excluding Loss Adjustment Expense', 'Paid Allocated Loss Adjustment Expense', 'Paid & Case Incurred Loss Excluding Loss Adjustment Expense', 'Paid & Case Allocated Loss Adjustment Expense']];
  const top = contact.length; // index of next row (0-based)
  const ext_ = `'Claims Data Extract'`;
  LOB_LIST.forEach(([code, name], i) => {
    const r = top + i + 1; // Excel row number
    const sumif = (col: string) => F(`SUMIFS(${ext_}!${col}$2:${col}$${n + 1},${ext_}!$A$2:$A$${n + 1},"${code}")`);
    const line = s.byLine.find((l) => l.lob === code);
    contact.push([bool(`AND(D${r}=E${r}+F${r}+G${r}+H${r},H${r}=SUM(I${r}:M${r}))`), `${code} ${name}`, '', sumif('D'), sumif('E'), sumif('F'), sumif('G'), sumif('H'), sumif('I'), sumif('J'), sumif('K'), sumif('L'), sumif('M'),
      F(`IF(D${r}=0,0,(G${r}+H${r})/D${r})`, PCT), { f: `SUMIFS(${ext_}!N$2:N$${n + 1},${ext_}!$A$2:$A$${n + 1},"${code}")`, z: USD },
      { v: line ? line.paidAlae : 0, z: USD }, { v: line ? line.incurred : 0, z: USD }, { v: 0, z: USD }]);
  });
  sheet('Contact and Statewide Modeling', contact, [60, 40, 30, ...Array(15).fill(20)]);

  // ── Validation Checks and Survey (questions numbered 1-37, one column per line of business) ──
  const per = (get: (x: SurveyData, code: string) => number): Cell[] => LOB_CODES.map((code) => ({ v: ['HO', 'DW', 'PF'].includes(code) ? get(s.surveyByLine[code] ?? emptySurvey(), code) : 0 }));
  const lineVal = (code: string, key: 'closedPay' | 'closedNoPay' | 'openPay' | 'openNoPay') => s.byLine.find((l) => l.lob === code)?.[key] ?? 0;
  const col = (i: number) => String.fromCharCode(68 + i); // D..M
  // off = number of rows above question 1 (header rows), so formulas point at the right Excel rows on each tab
  const build = (off: number): Row[] => {
    const rowOf = (qn: number) => qn + off;
    const sumRows = (from: number, to: number): Cell[] => LOB_CODES.map((_, i) => F(`SUM(${col(i)}${rowOf(from)}:${col(i)}${rowOf(to)})`));
    const zeros = (): number[] => LOB_CODES.map(() => 0);
    const q = (num: number, text: string, cells: (Cell | number)[]): Row => [num, 'As Set', text, ...cells.map((x) => (typeof x === 'number' ? { v: x } : x)),
      bool(`SUM(D${rowOf(num)}:M${rowOf(num)})>=0`), 'NO'];
    return [
      q(1, 'NUMBER OF CLAIMS CLOSED WITH PAYMENT (Sum Lines 2-5)', sumRows(2, 5)),
      q(2, '  Closed within 0-30 days', per((x) => x.closedWithPaymentByDays[0])), q(3, '  Closed within 31-60 days', per((x) => x.closedWithPaymentByDays[1])),
      q(4, '  Closed within 61-90 days', per((x) => x.closedWithPaymentByDays[2])), q(5, '  Closed over 90 days', per((x) => x.closedWithPaymentByDays[3])),
      q(6, 'NUMBER OF CLAIMS CLOSED WITHOUT PAYMENT (Sum Lines 7-10)', sumRows(7, 10)),
      q(7, '  Closed within 0-30 days', per((x) => x.closedWithoutPaymentByDays[0])), q(8, '  Closed within 31-60 days', per((x) => x.closedWithoutPaymentByDays[1])),
      q(9, '  Closed within 61-90 days', per((x) => x.closedWithoutPaymentByDays[2])), q(10, '  Closed over 90 days', per((x) => x.closedWithoutPaymentByDays[3])),
      q(11, 'CLAIMS CLOSED WITHOUT PAYMENT BY REASON (Lines 12 + 17)', LOB_CODES.map((_, i) => F(`${col(i)}${rowOf(12)}+${col(i)}${rowOf(17)}`))),
      q(12, '  Substantive reasons (Sum Lines 13-16)', sumRows(13, 16)),
      q(13, '    No flood coverage', zeros()),
      q(14, '    All other coverage exclusions or no policy in force', LOB_CODES.map((code) => lineVal(code, 'closedNoPay'))),
      q(15, '    Covered damage below deductible', zeros()), q(16, '    Fraud', zeros()),
      q(17, '  Administrative reasons (Sum Lines 18-22)', sumRows(18, 22)),
      q(18, '    Duplicate claim', zeros()), q(19, '    Claimant withdrew claim', zeros()), q(20, '    Unable to contact insured', zeros()),
      q(21, '    Loss not related to the event', zeros()), q(22, '    Other administrative reasons', zeros()),
      q(23, 'OPEN CLAIMS (a claim can fall in several status lines below, so lines 24-36 may add to more than this total)', LOB_CODES.map((code) => lineVal(code, 'openPay') + lineVal(code, 'openNoPay'))),
      q(24, '  Open claims in appraisal', per((x) => x.openInAppraisal)), q(25, '  Open claims in arbitration', zeros()), q(26, '  Open claims in mediation', zeros()),
      q(27, '  Open claims in litigation', per((x) => x.openInLitigation)), q(28, '  Open claims in other alternative dispute resolution', zeros()),
      q(29, '  Open claims with claimant attorney representation, not in litigation', per((x) => x.openAttorneyRepresented)),
      q(30, '  Open claims with public adjuster representation', per((x) => x.openPublicAdjuster)),
      q(31, '  Open claims waiting on contractors, tradesmen, engineers, or other specialists', per((x) => x.openWaitingOnContractors)),
      q(32, '  Open claims involving evaluation of wind versus flood damage', per((x) => x.openWindVsFlood)),
      q(33, '  Open claims awaiting information from the insured', zeros()),
      q(34, '  Reopened claims', per((x) => x.reopened)), q(35, '  Supplemental claims', per((x) => x.supplemental)),
      q(36, '  Open claims for other reasons', zeros()),
      [37, 'As Set', "Please describe the main reason(s) your company's claims remain open.", 'Claims remain open pending contractor estimates, supplemental documentation and appraisal or litigation where noted above.'],
    ];
  };
  const qHead: Row = ['Question', 'As Set', 'QUESTIONS', ...LOB_LIST.map(([, name]) => name.toUpperCase()), 'Error Messages', 'TRADE SECRET?'];
  sheet('Validation Checks', [qHead, ...build(1)], [10, 10, 70, ...Array(10).fill(16), 14, 14]);
  sheet('Survey', [['Survey (enhanced filing only)'], qHead, ...build(2)], [10, 10, 70, ...Array(10).fill(16), 14, 14]);

  // ── Valid Responses ──
  const pairs = new Map<string, string>();
  s.rows.forEach((x) => { if (x.county && /^\d{5}$/.test(x.zip)) pairs.set(`${x.county}|${x.zip}`, x.county); });
  const pairList = [...pairs.keys()].map((k) => k.split('|') as [string, string]);
  pairList.push(['Unknown', 'Unknown']);
  const vr: Row[] = [['LINE OF BUSINESS', 'DETAILS', 'COUNTY', 'ZIP']];
  for (let i = 0; i < Math.max(LOB_LIST.length, pairList.length); i++) vr.push([LOB_LIST[i]?.[0] ?? '', LOB_LIST[i]?.[1] ?? '', pairList[i]?.[0] ?? '', pairList[i]?.[1] ?? '']);
  vr.push([''], ['Note: county and ZIP pairs listed are those present in this filing. Replace with the full OIR Valid Responses list for complete pairing verification.']);
  sheet('Valid Responses', vr, [18, 40, 18, 12]);

  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' }) as ArrayBuffer;
  return new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}
