// Builds the Florida OIR Catastrophe Reporting Form (CRF-26A, version 26.01.A) workbook from claim data.
// Layout follows the tabs in OIR's 2026 template: Version, Contacts, Summary, Claims Data Extract, Survey, Valid Responses.
// IRFS rejects a filing unless every validation shows TRUE, and OIR re-issues the template with each data call, so a
// first filing may need these figures pasted into the template OIR sends with the notice.
import type { ComplianceSummary, SurveyData } from '../models/compliance/complianceModel';

export interface CrfContact {
  preparer: string; email: string; phone: string; companyName: string; naicCode: string; floridaCompanyCode: string; fein: string; groupCode: string; domicile: string;
  grossPayable: number; reinsurance: number; model: string; howEvaluated: string;
}

export const FL_COUNTIES = ['Alachua', 'Baker', 'Bay', 'Bradford', 'Brevard', 'Broward', 'Calhoun', 'Charlotte', 'Citrus', 'Clay', 'Collier', 'Columbia', 'DeSoto', 'Dixie', 'Duval',
  'Escambia', 'Flagler', 'Franklin', 'Gadsden', 'Gilchrist', 'Glades', 'Gulf', 'Hamilton', 'Hardee', 'Hendry', 'Hernando', 'Highlands', 'Hillsborough', 'Holmes', 'Indian River',
  'Jackson', 'Jefferson', 'Lafayette', 'Lake', 'Lee', 'Leon', 'Levy', 'Liberty', 'Madison', 'Manatee', 'Marion', 'Martin', 'Miami-Dade', 'Monroe', 'Nassau', 'Okaloosa',
  'Okeechobee', 'Orange', 'Osceola', 'Palm Beach', 'Pasco', 'Pinellas', 'Polk', 'Putnam', 'Santa Rosa', 'Sarasota', 'Seminole', 'St. Johns', 'St. Lucie', 'Sumter', 'Suwannee',
  'Taylor', 'Union', 'Volusia', 'Wakulla', 'Walton', 'Washington'];
export const LOB_CODES = ['HO', 'DW', 'MHO', 'CR', 'CP', 'PF', 'BI', 'CPD', 'PPAD', 'AC', 'BM', 'FI', 'FMP', 'GL', 'IEC', 'IF', 'IM', 'MPC', 'OM'];

const LINE_COLS: [string, string][] = [['HO', 'Homeowners'], ['DW', 'Dwelling'], ['PF', 'Private Flood (Stand-Alone)']];

export async function buildCrfWorkbook(s: ComplianceSummary, c: CrfContact, asOf: string): Promise<Blob> {
  const XLSX = await import('xlsx');
  const wb = XLSX.utils.book_new();
  const eventName = s.event?.eventName ?? 'ALL EVENTS';
  const add = (name: string, rows: unknown[][]) => XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), name);

  add('Version', [['Form version', 'CRF-26A 26.01.A'], ['Event name', eventName.toUpperCase()], ['Trade Secret?', 'NO'],
    ['Note', 'Generated by LAELia from claim data. Confirm against the OIR data call notice before filing in IRFS.']]);

  const net = c.grossPayable - c.reinsurance;
  add('Contacts', [['Field', 'Value'],
    ['As-of date of data submitted', asOf], ['Name of individual who completed form', c.preparer], ['Individual\'s email address', c.email], ['Individual\'s phone number', c.phone],
    ['Company Name', c.companyName], ['Company NAIC Code', c.naicCode], ['Company Florida Company Code', c.floridaCompanyCode], ['Company FEIN', c.fein], ['Company Group Code', c.groupCode],
    ['Company State of Domicile', c.domicile], ['Is this filing being submitted as trade secret?', 'No'],
    ['Dollar Amount of Estimated Gross Payable Loss from Event (Gross of Reinsurance)', c.grossPayable],
    ['Projected Net Retention Resulting from the Event', net], ['Dollar Amount of Estimated Payable Loss covered by Reinsurance or Other Loss-Transfer Agreements', c.reinsurance],
    ['Check: gross = net retention + reinsurance', { f: 'B13=B14+B15' }], ['Model and Version', c.model || 'N/A'], ['If model is N/A, how losses were evaluated', c.howEvaluated]]);

  const sumHead = ['Line of Business', 'Policies in Force (Florida Only)', 'Number of Claims Reported (Florida Only)', 'Number of Open Claims with Payment', 'Number of Open Claims without Payment',
    'Number of Claims Closed with Payment', 'Number of Claims Closed without Payment', 'Closed without Payment (No Flood Coverage)',
    'Closed without Payment (All Other Coverage Exclusions or No Policy in Force)', 'Closed without Payment (Covered Damage Below Deductible)', 'Closed without Payment (Fraud)',
    'Closed without Payment (For Administrative Reasons)', 'Percent of Claims Closed', 'Paid Loss Excluding Loss Adjustment Expense', 'Paid Allocated Loss Adjustment Expense',
    'Paid & Case Incurred Loss Excluding Loss Adjustment Expense', 'Paid & Case Allocated Loss Adjustment Expense', 'Required Claims and Paid Losses?'];
  const sumRows: unknown[][] = [sumHead];
  s.byLine.forEach((l, i) => {
    const r = i + 2;
    sumRows.push([l.lobName, '', l.claims, l.openPay, l.openNoPay, l.closedPay, l.closedNoPay, 0, l.closedNoPay, 0, 0, 0, { f: `IF(C${r}=0,0,(F${r}+G${r})/C${r})` }, l.paidLoss, l.paidAlae, l.incurred, '',
      { f: `AND(D${r}+E${r}+F${r}+G${r}=C${r},G${r}=SUM(H${r}:L${r}))` }]);
  });
  const last = s.byLine.length + 1;
  sumRows.push(['Totals', '', ...['C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L'].map((col) => ({ f: `SUM(${col}2:${col}${last})` })), '', ...['N', 'O', 'P'].map((col) => ({ f: `SUM(${col}2:${col}${last})` }))]);
  add('Summary', sumRows);

  const extHead = ['Line of Business (code)', 'County in Which Claim Occurred', 'Zip Code in Which Claim Occurred', 'Number of Claims Reported (Florida Only)', 'Number of Open Claims With Payment',
    'Number of Open Claims Without Payment', 'Number of Claims Closed With Payment', 'Number of Claims Closed Without Payment', 'Closed Without Payment (No Flood Coverage)',
    'Closed Without Payment (All Other Coverage Exclusions or No Policy in Force)', 'Closed Without Payment (Covered Damage Below Deductible)', 'Closed Without Payment (Fraud)',
    'Closed Without Payment (For Administrative Reasons)', 'Paid Loss Excluding Loss Adjustment Expense',
    'Check #1: LOB and county valid', 'Check #3: categories equal claims reported', 'Check #4: zero claims means zero loss', 'Check #5: no payments means zero loss'];
  const ext: unknown[][] = [extHead];
  s.rows.forEach((x, i) => {
    const r = i + 2;
    ext.push([x.lob, x.county, x.zip, x.claims, x.openPay, x.openNoPay, x.closedPay, x.closedNoPay, 0, x.closedNoPay, 0, 0, 0, x.paidLoss,
      { f: `AND(COUNTIF('Valid Responses'!A:A,A${r})>0,COUNTIF('Valid Responses'!C:C,B${r})>0)` }, { f: `E${r}+F${r}+G${r}+H${r}=D${r}` },
      { f: `IF(D${r}=0,N${r}=0,TRUE)` }, { f: `IF(E${r}+G${r}=0,N${r}=0,TRUE)` }]);
  });
  add('Claims Data Extract', ext);

  const sv = (f: (x: SurveyData) => number): unknown[] => LINE_COLS.map(([k]) => f(s.surveyByLine[k] ?? emptySurvey()));
  const days = (kind: 'closedWithPaymentByDays' | 'closedWithoutPaymentByDays', i: number) => sv((x) => x[kind][i]);
  const survey: unknown[][] = [['Survey item', ...LINE_COLS.map(([, n]) => n)],
    ['Claims closed with payment', ...LINE_COLS.map((_, j) => ({ f: `SUM(${'BCD'[j]}3:${'BCD'[j]}6)` }))],
    ['  Closed within 0-30 days', ...days('closedWithPaymentByDays', 0)], ['  Closed within 31-60 days', ...days('closedWithPaymentByDays', 1)],
    ['  Closed within 61-90 days', ...days('closedWithPaymentByDays', 2)], ['  Closed over 90 days', ...days('closedWithPaymentByDays', 3)],
    ['Claims closed without payment', ...LINE_COLS.map((_, j) => ({ f: `SUM(${'BCD'[j]}8:${'BCD'[j]}11)` }))],
    ['  Closed within 0-30 days', ...days('closedWithoutPaymentByDays', 0)], ['  Closed within 31-60 days', ...days('closedWithoutPaymentByDays', 1)],
    ['  Closed within 61-90 days', ...days('closedWithoutPaymentByDays', 2)], ['  Closed over 90 days', ...days('closedWithoutPaymentByDays', 3)],
    ['Open claims in appraisal', ...sv((x) => x.openInAppraisal)], ['Open claims in arbitration', 0, 0, 0], ['Open claims in mediation', 0, 0, 0],
    ['Open claims in litigation', ...sv((x) => x.openInLitigation)], ['Open claims in other alternative dispute resolution', 0, 0, 0],
    ['Open claims with claimant attorney representation, not in litigation', ...sv((x) => x.openAttorneyRepresented)],
    ['Open claims with public adjuster representation', ...sv((x) => x.openPublicAdjuster)],
    ['Open claims waiting on contractors, tradesmen, engineers, or other specialists', ...sv((x) => x.openWaitingOnContractors)],
    ['Open claims involving evaluation of wind versus flood damage', ...sv((x) => x.openWindVsFlood)], ['Reopened claims', ...sv((x) => x.reopened)], ['Supplemental claims', ...sv((x) => x.supplemental)]];
  add('Survey', survey);

  const vr: unknown[][] = [['Line of Business codes', '', 'Florida counties']];
  for (let i = 0; i < Math.max(LOB_CODES.length, FL_COUNTIES.length); i++) vr.push([LOB_CODES[i] ?? '', '', FL_COUNTIES[i] ?? '']);
  add('Valid Responses', vr);

  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array' }) as ArrayBuffer;
  return new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

function emptySurvey(): SurveyData {
  return { closedWithPaymentByDays: [0, 0, 0, 0], closedWithoutPaymentByDays: [0, 0, 0, 0], openInAppraisal: 0, openInLitigation: 0, openAttorneyRepresented: 0,
    openPublicAdjuster: 0, openWaitingOnContractors: 0, openWindVsFlood: 0, reopened: 0, supplemental: 0 };
}
